ORDER = ["floor", "wall", "water", "lava", "stairs", "sealed", "hero", "potion",
         "greater", "gold", "weapon", "armor", "beast", "humanoid", "undead", "large",
         "caster", "boss"]
COLS = 8
CELL = 16


def grid(name):
    rows = [r for r in T[name].strip("\n").split("\n")]
    assert len(rows) == 16, (name, len(rows))
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
    return rows


def main():
    out_dir = os.path.join(os.path.dirname(__file__), "..", "art")
    os.makedirs(out_dir, exist_ok=True)
    nrows = (len(ORDER) + COLS - 1) // COLS
    img = Image.new("RGBA", (COLS * CELL, nrows * CELL), (0, 0, 0, 0))
    for i, name in enumerate(ORDER):
        ox, oy = (i % COLS) * CELL, (i // COLS) * CELL
        for y, row in enumerate(grid(name)):
            for x, ch in enumerate(row):
                img.putpixel((ox + x, oy + y), PAL[ch])
    img.save(os.path.join(out_dir, "tiles.png"))
    # 6x preview on a dark background, for humans
    prev = Image.new("RGBA", img.size, (12, 12, 20, 255))
    prev.alpha_composite(img)
    prev.resize((img.width * 6, img.height * 6), Image.NEAREST).save(os.path.join(out_dir, "tiles_preview.png"))
    print("Wrote art/tiles.png", img.size)


if __name__ == "__main__":
    main()
